// Derive overrides from every deployed stylesheet, including scoped lazy pages.
// Keep all selectors, conditional rules, and alpha values; replace backgrounds only.
const fs=require('node:fs'),path=require('node:path');
const postcss=require('postcss');
const parser=require('node:module').createRequire(require.resolve('tailwindcss'))('postcss-selector-parser');
const input=path.resolve('../sub2api-ui-audit-20261104/neutral-source-css');
const output=postcss.root();
const seen=new Set();let changed=0;
const replace=value=>value.replace(/#334155([0-9a-f]{2})?(?![0-9a-f])/gi,(_,alpha)=>'#2a2a2a'+(alpha||''))
 .replace(/\b(rgb|rgba)\(\s*51\s+65\s+85(?=\s|\)|\/)/gi,'$1(42 42 42')
 .replace(/\b(rgb|rgba)\(\s*51\s*,\s*65\s*,\s*85(?=\s|\)|,)/gi,'$1(42,42,42');
function strengthen(selector){
 return parser(selectors=>selectors.each(sel=>{
  const pseudo=sel.nodes.find(n=>n.type==='pseudo'&&n.value.startsWith('::'));
  const guard=parser().astSync(':not([data-preserve-surface])').first.first.clone();
  if(pseudo)sel.insertBefore(pseudo,guard);else sel.append(guard);
 })).processSync(selector);
}
for(const file of fs.readdirSync(input).sort()){
 if(!file.endsWith('.css'))continue;
 const root=postcss.parse(fs.readFileSync(path.join(input,file),'utf8'));
 root.walkRules(rule=>{
  const chain=[];for(let p=rule.parent;p&&p.type!=='root';p=p.parent)if(p.type==='atrule')chain.unshift(p);
  if(chain.some(a=>/keyframes$/i.test(a.name)))return;
  const decls=[];
  rule.each(d=>{if(d.type!=='decl'||!(/^(background(?:-color|-image)?|--tw-gradient(?:-.+)?)$/.test(d.prop)))return;
   const value=replace(d.value);if(value!==d.value)decls.push(postcss.decl({prop:d.prop,value,important:true}));
  });
  if(!decls.length)return;
  const selector=strengthen(rule.selector),key=chain.map(c=>c.name+c.params).join('|')+selector+decls.map(d=>d.toString()).join(';');
  if(seen.has(key))return;seen.add(key);changed+=decls.length;
  let parent=output;for(const a of chain){const n=postcss.atRule({name:a.name,params:a.params});parent.append(n);parent=n;}
  const r=postcss.rule({selector});r.append(decls);parent.append(r);
 });
}
const css='/* Neutral surface color: #334155 -> #2a2a2a. Generated by tools/build_neutral_surfaces.cjs. */\n'+output.toString();
fs.writeFileSync('src/styles/neutral-surfaces.css',css+'\n');
console.log(JSON.stringify({rules:seen.size,backgroundDeclarations:changed,bytes:css.length}));
